// SaveStatusState 只落状态流字段（status/other_info + 多key 状态），防止过期快照
// 覆盖凭证。与 Channel.saveStatusState 同构；导出供套餐自动启停任务（service 层）
// 写账户滞回状态。
func (account *Account) SaveStatusState() error {
	if account.Id == 0 {
		return errors.New("account ID is 0")
	}
	updates := map[string]any{
		"status":     account.Status,
		"other_info": account.OtherInfo,
	}
	if account.ChannelInfo.IsMultiKey {
		updates["channel_info"] = account.ChannelInfo
	}
	return DB.Model(&Account{}).Where("id = ?", account.Id).Updates(updates).Error
}

// ── 账户轮询锁（按账户 id；共享账户跨渠道并发轮询安全） ─────────────

var accountPollingLocks sync.Map

// GetAccountPollingLock 返回/创建账户级轮询锁。
func GetAccountPollingLock(accountId int) *sync.Mutex {
	if lock, exists := accountPollingLocks.Load(accountId); exists {
		return lock.(*sync.Mutex)
	}
	newLock := &sync.Mutex{}
	actual, _ := accountPollingLocks.LoadOrStore(accountId, newLock)
	return actual.(*sync.Mutex)
}

