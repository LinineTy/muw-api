// Delete 删除账户：仍有渠道引用时拒绝（先解绑/删除渠道）。引用关系以绑定表为准。
func (account *Account) Delete() error {
	count, err := CountChannelsBoundToAccount(account.Id)
	if err != nil {
		return err
	}
	if count > 0 {
		return fmt.Errorf("账户仍被 %d 个渠道引用，请先删除或解绑相关渠道", count)
	}
	return DB.Delete(account).Error
}

// GetAccountById 查单个账户；selectAll=false 时 Omit key（列表/详情脱敏路径）。
func GetAccountById(id int, selectAll bool) (*Account, error) {
	account := &Account{Id: id}
	var err error
	if selectAll {
		err = DB.First(account, "id = ?", id).Error
	} else {
		err = DB.Omit("key", "coding_plan_key").First(account, "id = ?", id).Error
	}
	if err != nil {
		return nil, err
	}
	return account, nil
}

// maskAccountSecrets 用已加载的明文算出脱敏预览（列表这类只读路径用）。
// 注意：不要在这里清掉 Key 本身——controller 的 fillAccountView 还会用同一份
// 明文再算一次预览，清早了会把 key_masked 覆盖成空串。明文不会下发：
// Account.Key / CodingPlanKey 的 json 标签都是 "-"。
