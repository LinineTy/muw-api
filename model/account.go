// GetKeys 解析账户 key 列表：JSON 数组（Vertex AI 场景）或换行分隔。
func (account *Account) GetKeys() []string {
	if account.Key == "" {
		return []string{}
	}
	trimmed := strings.TrimSpace(account.Key)
	if strings.HasPrefix(trimmed, "[") {
		if arr, ok := parseKeyJSONArray(trimmed); ok {
			return arr
		}
	}
	return strings.Split(strings.Trim(account.Key, "\n"), "\n")
}

// parseKeyJSONArray 解析 JSON 数组格式的 key 列表（Vertex AI 多密钥对象）。
func parseKeyJSONArray(raw string) ([]string, bool) {
	var arr []json.RawMessage
	if err := common.Unmarshal([]byte(raw), &arr); err != nil {
		return nil, false
	}
	res := make([]string, len(arr))
	for i, v := range arr {
		res[i] = string(v)
	}
	return res, true
}

// GetNextEnabledKey 按 ChannelInfo.MultiKeyMode 返回一个可用 key。
// 多渠道共享同一账户（缓存路径共享 *Account 指针 / DB 路径每次新查），轮询索引与
// key 启停状态都在 account.ChannelInfo 上，锁按账户 id——共享账户的并发轮询安全。
func (account *Account) GetNextEnabledKey() (string, int, *types.NewAPIError) {
	if !account.ChannelInfo.IsMultiKey {
		return account.Key, 0, nil
	}
	keys := account.GetKeys()
	if len(keys) == 0 {
		return "", 0, types.NewError(errors.New("no keys available"), types.ErrorCodeChannelNoAvailableKey)
	}

	lock := GetAccountPollingLock(account.Id)
	lock.Lock()
	defer lock.Unlock()

	statusList := account.ChannelInfo.MultiKeyStatusList
	getStatus := func(idx int) int {
		if statusList == nil {
			return common.ChannelStatusEnabled
		}
		if status, ok := statusList[idx]; ok {
			return status
		}
		return common.ChannelStatusEnabled
	}

	enabledIdx := make([]int, 0, len(keys))
	for i := range keys {
		if getStatus(i) == common.ChannelStatusEnabled {
			enabledIdx = append(enabledIdx, i)
		}
	}
	if len(enabledIdx) == 0 {
		return "", 0, types.NewError(errors.New("no enabled keys"), types.ErrorCodeChannelNoAvailableKey)
	}

	switch account.ChannelInfo.MultiKeyMode {
	case constant.MultiKeyModeRandom:
		selectedIdx := enabledIdx[rand.Intn(len(enabledIdx))]
		return keys[selectedIdx], selectedIdx, nil
	case constant.MultiKeyModePolling:
		defer func() {
			// DB 路径（非内存缓存）把轮询索引落库；缓存路径共享指针即时可见。
			if !common.MemoryCacheEnabled {
				_ = account.SaveChannelInfo()
			}
		}()
		start := account.ChannelInfo.MultiKeyPollingIndex
		if start < 0 || start >= len(keys) {
			start = 0
		}
		for i := 0; i < len(keys); i++ {
			idx := (start + i) % len(keys)
			if getStatus(idx) == common.ChannelStatusEnabled {
				account.ChannelInfo.MultiKeyPollingIndex = (idx + 1) % len(keys)
				return keys[idx], idx, nil
			}
		}
		return keys[enabledIdx[0]], enabledIdx[0], nil
	default:
		return keys[enabledIdx[0]], enabledIdx[0], nil
	}
}

